import { Polygon } from "geojson";
type Feature = {
  type: "Feature";
  properties: Record<string, any>;
  geometry: Polygon;
};

type FeatureCollection = {
  type: "FeatureCollection";
  features: Feature[];
};

export function toGeoJSONCollection(
  cityPolygon: Polygon,
  polygons: Polygon[],
  b: Polygon,
  polygons2?: Polygon[],
): FeatureCollection {
  return {
    type: "FeatureCollection",
    features: [
      // ✅ City boundary (BIG polygon)
      {
        type: "Feature",
        properties: {
          id: "city",
          label: "City Boundary",
          type: "city",
        },
        geometry: cityPolygon,
      },
      {
        type: "Feature",
        properties: {
          id: "Home",
          label: "Home Boundary",
          type: "Home",
        },
        geometry: b,
      },

      // ✅ Other polygons (zones / H3 groups)
      ...polygons.map((polygon, index) => ({
        type: "Feature" as const,
        properties: {
          id: index,
          label: `Polygon ${index + 1}`,
          type: "zone",
        },
        geometry: polygon,
      })),
      ...(polygons2 ?? []).map((polygon, index) => ({
        type: "Feature" as const,
        properties: {
          id: index + size,
          label: `Polygon ${index + size + 1}`,
          type: "zone",
        },
        geometry: polygon,
      })),
    ],
  };
}

